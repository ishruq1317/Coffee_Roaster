export const CURRENCY_RATES: Record<Currency, { rate: number; symbol: string; prefix: boolean }> = {
  EUR: { rate: 1.0, symbol: '€', prefix: false },
  GBP: { rate: 0.85, symbol: '£', prefix: true },
  CHF: { rate: 0.95, symbol: 'CHF', prefix: false },
};

export const formatPrice = (priceEUR: number, currency: Currency): string => {
  const info = CURRENCY_RATES[currency];
  const converted = (priceEUR * info.rate).toFixed(2);
  return info.prefix ? `${info.symbol}${converted}` : `${converted} ${info.symbol}`;
};

